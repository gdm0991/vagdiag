def describe(code):
    """
    Возвращает описание кода. Для стандартных — точное,
    для кодов производителя — структурное, по разбору самого номера.
    """
    if not code or len(code) < 5:
        return ""
    code = code.upper()
    if code in KNOWN:
        return KNOWN[code]

    letter = code[0]
    manufacturer = code[1] == "1"
    system = SYSTEMS.get(letter, "неизвестная система")

    if letter == "P" and len(code) >= 3:
        subsystem = SUBSYSTEMS.get(code[2], "")
        if manufacturer:
            return (f"Код производителя, {system}"
                    + (f", {subsystem}" if subsystem else "")
                    + ". Точное описание есть только в базе изготовителя")
        return f"Стандартный код, {system}" + (f", {subsystem}" if subsystem else "")

    if manufacturer:
        return f"Код производителя, {system}"
    return f"Стандартный код, {system}"


def is_serious(code):
    """
    Отмечает коды, с которыми лучше не ездить: пропуски воспламенения
    убивают катализатор, а потеря связи с блоком двигателя
    может остановить автомобиль на ходу.
    """
    if not code:
        return False
    code = code.upper()
    return (code.startswith("P030") or code.startswith("U010")
            or code in ("P0601", "P0605", "P0600", "P0335"))
