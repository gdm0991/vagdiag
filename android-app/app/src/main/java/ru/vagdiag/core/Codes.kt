    fun describe(code: String): String {
        if (code.length < 5) return ""
        val upper = code.uppercase()
        known[upper]?.let { return it }

        val letter = upper[0]
        val manufacturer = upper[1] == '1'
        val system = systems[letter] ?: "неизвестная система"

        if (letter == 'P') {
            val subsystem = subsystems[upper[2]]
            val tail = if (subsystem != null) ", $subsystem" else ""
            return if (manufacturer)
                "Код производителя, $system$tail. Точное описание есть только в базе изготовителя"
            else "Стандартный код, $system$tail"
        }
        return if (manufacturer) "Код производителя, $system" else "Стандартный код, $system"
    }

    /**
     * Коды, с которыми лучше не ездить: пропуски воспламенения убивают
     * катализатор, а потеря связи с блоком двигателя может остановить
     * автомобиль на ходу.
     */
    fun isSerious(code: String): Boolean {
        val upper = code.uppercase()
        return upper.startsWith("P030") || upper.startsWith("U010") ||
                upper in setOf("P0601", "P0605", "P0600", "P0335")
    }
